def add_demo_deals(db: Session, owner: str) -> None:
    """Adds a fresh copy of every demo deal owned by `owner`. Doesn't commit.
    Each one is validated through the same schema as POST /deals."""
    # Imported here: app.api.deals imports app.auth, which calls this.
    from app.api.deals import _column_values
    from app.api.schemas import DealCreate
    from app.models.deal import Deal

    # The deal list sorts by created_at, so step it to keep this file's order
    # (one insert batch would otherwise share a timestamp and sort by random id).
    start = datetime.now(UTC)
    for i, raw in enumerate(DEMO_DEALS):
        payload = DealCreate.model_validate(raw)
        created = start + timedelta(milliseconds=i)
        db.add(Deal(**_column_values(payload), owner_id=owner, created_at=created))
